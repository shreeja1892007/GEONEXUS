export function getServiceById(id: string): CitizenServiceDefinition | undefined {
  return CITIZEN_SERVICE_CATALOG.find((s) => s.id === id);
}

export function getServicesByCategory(): Record<string, CitizenServiceDefinition[]> {
  const map: Record<string, CitizenServiceDefinition[]> = {};
  for (const service of CITIZEN_SERVICE_CATALOG) {
    if (!map[service.category]) map[service.category] = [];
    map[service.category].push(service);
  }
  return map;
}

