export function findParcelsByQuery(query: string): {
  parcels: Parcel[];
  detectedType: 'Survey Number' | 'ULPIN' | 'Property ID' | 'Registration Document' | 'Locality / Address';
} {
  const q = query.trim();
  if (!q) return { parcels: [], detectedType: 'Survey Number' };

  let detectedType: 'Survey Number' | 'ULPIN' | 'Property ID' | 'Registration Document' | 'Locality / Address' =
    'Locality / Address';

  // Smart Detection Heuristic
  if (q.includes('/') || /^\d+[a-zA-Z]*\/\d+[a-zA-Z]*$/.test(q)) {
    detectedType = 'Survey Number';
  } else if (/^[A-Za-z]{2}\d{2}[A-Za-z]{3}\d{7}$/i.test(q) || q.toUpperCase().startsWith('TN01')) {
    detectedType = 'ULPIN';
  } else if (q.toUpperCase().startsWith('PROP') || q.toUpperCase().startsWith('PT-')) {
    detectedType = 'Property ID';
  } else if (q.toUpperCase().startsWith('REG-') || q.toUpperCase().startsWith('MORT-') || /^\d{4}\/\d{4}$/.test(q)) {
    detectedType = 'Registration Document';
  }

  const cleanQ = q.toUpperCase();
  const matched = MOCK_PARCELS.filter((p) => {
    return (
      p.surveyNumber.toUpperCase().includes(cleanQ) ||
      p.ulpin.toUpperCase().includes(cleanQ) ||
      p.village.toUpperCase().includes(cleanQ) ||
      p.district.toUpperCase().includes(cleanQ) ||
      p.tax.assessmentNumber.toUpperCase().includes(cleanQ) ||
      p.registrations.some((r) => r.registrationNumber.toUpperCase().includes(cleanQ))
    );
  });

  return { parcels: matched, detectedType };
}

const APPLICATIONS_STORAGE_KEY = 'land_stack_citizen_applications';

export function getStoredApplications(): CitizenApplication[] {
  try {
    const raw = localStorage.getItem(APPLICATIONS_STORAGE_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch {
    // ignore
  }
  return MOCK_APPLICATIONS;
}

export function addApplication(app: CitizenApplication): void {
  try {
    const current = getStoredApplications();
    const updated = [app, ...current];
    localStorage.setItem(APPLICATIONS_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    MOCK_APPLICATIONS.unshift(app);
  }
}

